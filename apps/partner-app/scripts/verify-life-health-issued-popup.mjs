import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const screen=readFileSync(new URL("../app/life-health-cases/index.tsx", import.meta.url),"utf8");
const api=readFileSync(new URL("../lib/life-health-cases.ts", import.meta.url),"utf8");
const route=readFileSync(new URL("../../web-portal/app/api/partner/life-health-cases/route.ts", import.meta.url),"utf8");
assert.match(screen, /row\.status_group==='issued' && row\.final_policy_id \? setIssuedCase\(row\) : router\.push/, "Only issued cases show popup, pending/rejected remain unchanged");
assert.match(screen,/Policy already issued/);
assert.match(screen,/This case has already been issued as a policy\./);
assert.match(screen,/onRequestClose=\{\(\)=>setIssuedCase\(null\)\}/);
assert.match(screen,/onPress=\{\(\)=>setIssuedCase\(null\)\}/);
assert.match(screen,/router\.push\(\`\/policy\/\$\{policyId\}\` as never\)/, "Issued View Policy opens native Policy Details by final policy ID");
assert.match(screen,/const policyId=issuedCase\.final_policy_id/, "Use the linked issued policy ID, not the case ID");
assert.doesNotMatch(screen,/router\.push\(\`\/life-health-cases\/\$\{caseId\}\`/, "Issued popup must not route to Case Details");
assert.doesNotMatch(screen,/Linking\.openURL/, "Issued popup must not open a browser");
assert.match(api,/export async function saveLifeHealthCaseEdit/, "Native save client is available");
assert.match(route,/export async function POST\(request: Request\)/, "Scoped native write endpoint is available");
assert.match(route,/canAccessPolicy\(profile\.id,profile\.role,row\.final_policy_id!/, "Issued edits require scoped policy access");
assert.match(route,/final_policy_id/, "Scoped list returns final policy ID");
assert.match(screen,/Load More Cases<\/Text>/, "Case list uses the same Load More label pattern as Policies");
assert.match(screen,/<Feather name="chevron-down" size=\{13\} color="#3156B8"\/>/, "Case list has the Policies downward chevron");
assert.match(screen,/Loading more cases…/, "Case list has loading progress text");
assert.match(screen,/rows\.length<total\?<Pressable/, "Case footer is hidden after all matching cases are loaded");
assert.match(screen,/listLifeHealthCases\(\{status,search,offset,limit:10\}\)/, "Existing 10-item server pagination is unchanged");
assert.match(screen,/accessibilityState=\{\{disabled:more,busy:more\}\}/, "Loading state disables repeated pagination taps");
assert.doesNotMatch(screen,/Load More \(\$\{rows\.length\} of \$\{total\}\)/, "Old numeric footer is removed");
console.log("Partner issued policy popup, native detail and scoped edits passed");
