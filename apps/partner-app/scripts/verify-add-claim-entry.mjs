import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const read = (relative) => readFileSync(fileURLToPath(new URL(relative, import.meta.url)), 'utf8');
const claims = read('../app/(tabs)/claims.tsx');
const route = read('../app/_layout.tsx');
const screen = read('../app/claim/new.tsx');
assert.match(claims, /router\.push\('\/claim\/new'/);
assert.match(claims, /styles\.addClaimButton/);
assert.ok(claims.indexOf('styles.addClaimButton') > claims.indexOf('styles.summaryRow'));
assert.match(route, /name="claim\/new"/);
assert.match(screen, /CLAIM_STAGES\.map/);
assert.match(screen, /Stage 1 of 9/);
assert.match(screen, /Customer \*/);
assert.match(screen, /Vehicle \*/);
assert.match(screen, /Spot photographs \/ documents/);
assert.doesNotMatch(screen, /supabase\.from\(|supabase\.rpc\(/, 'No unverified claim mutation');
assert.match(screen, /Saving and stage progression are disabled/);
console.log('Partner Add Claim nine-stage entry UI regression passed');
