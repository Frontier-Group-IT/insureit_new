import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { allocateFairSamples, acceptanceGate, selectTopInsurers, sanitizeCandidatePatch } from "../lib/policy-ocr-orchestrator.ts";

assert.deepEqual(selectTopInsurers({ A: 5, B: 20, C: 10, D: 1 }, 3), ["B", "C", "A"]);
const samples = ["a1", "a2", "b1", "c1"].map((id, index) => ({ id, insurer: index < 2 ? "A" : id.startsWith("b") ? "B" : "C", product: "motor", layout: "standard", createdAt: `2026-01-0${index + 1}` }));
assert.deepEqual(allocateFairSamples(samples, 3).map((sample) => sample.id), ["a1", "b1", "c1"]);
assert.equal(acceptanceGate({ fieldAccuracy: 0.95, wrongFinancialValues: 0, freshSiblingCounts: { A: 3 }, holdoutFailures: 0, budgetExhausted: false }).accepted, true);
assert.equal(acceptanceGate({ fieldAccuracy: 0.99, wrongFinancialValues: 1, freshSiblingCounts: { A: 3 }, holdoutFailures: 0, budgetExhausted: false }).reason, "wrong_financial_value");
assert.match(sanitizeCandidatePatch({ insurer: "A", product: "motor", layout: "x", rule: "remove 9876543210123456" }).rule, /redacted/);
const root = process.cwd();
const actions = fs.readFileSync(path.join(root, "app/policies/ocr-training-orchestrator-actions.ts"), "utf8");
const page = fs.readFileSync(path.join(root, "app/policies/ocr-training/page.tsx"), "utf8");
const migration = fs.readFileSync(path.join(root, "../../supabase/migrations/20260907170000_policy_ocr_training_orchestrator.sql"), "utf8");
const schemaWorkflow = fs.readFileSync(path.join(root, "../../.github/workflows/apply-policy-ocr-reviewer-tasks.yml"), "utf8");
const deployWorkflow = fs.readFileSync(path.join(root, "../../.github/workflows/deploy-production.yml"), "utf8");
assert.match(actions, /createPolicyOcrTrainingRun/);
assert.match(actions, /startPolicyOcrTrainingRun/);
assert.match(actions, /stopPolicyOcrTrainingRun/);
assert.match(actions, /recordPolicyOcrSatisfaction/);
assert.doesNotMatch(actions, /pending_it_approval|approvePolicyOcrChangeProposal|createPolicyOcrProposalFromFeedback/);
assert.match(page, /satisfactionTasks/);
assert.match(page, /recordPolicyOcrSatisfaction/);
assert.match(migration, /policy_ocr_training_orchestrators/);
assert.match(migration, /awaiting_satisfaction/);
assert.match(migration, /v_fresh_ready/);
assert.match(schemaWorkflow, /20260907170000_policy_ocr_training_orchestrator\.sql/);
assert.match(deployWorkflow, /20260907170000_policy_ocr_training_orchestrator\.sql/);
console.log("Policy OCR orchestrator regression passed.");
