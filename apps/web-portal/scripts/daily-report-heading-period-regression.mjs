import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(new URL(p,import.meta.url),"utf8");
const layout=read("../app/reports/(workspace)/layout.tsx");
const page=read("../app/reports/(workspace)/daily/page.tsx");
const header=read("../components/reports/daily-report-header-controls.tsx");
const period=read("../lib/reports/daily-report-period.ts");
const loader=read("../lib/reports/daily-self-activity.ts");
const endpoint=read("../app/api/reports/daily/employees/route.ts");

assert.match(layout, /<h1>Reports<\/h1>/);
assert.match(layout, /<DailyReportHeaderScopes canViewAll=\{canViewAll\} \/>/, "Employee selector receives report access");
assert.match(layout, /<DailyReportHeaderPeriod\s*\/>/, "Period dropdown at right of Reports header");
assert.match(header, /if\(!isDaily\) return null/, "Daily header controls are hidden on other reporting pages");
assert.match(header, /aria-label="Daily Report employee selector"/);
assert.match(header, /aria-haspopup="listbox"/, "Self and All must use a dropdown instead of segmented navigation");
assert.match(header, /type="search" aria-label="Search employee name or code"/, "Employee dropdown must be searchable");
assert.match(header, /const allSelected=canViewAll && searchParams.get\("scope"\)==="all"/, "Self remains selected by default without All selection");
assert.match(header, /matching\.map\(person=>\(/, "Authorized employee names appear in dropdown");
assert.match(header, /params.set\("scope",personId!==null && canViewAll\?"all":"self"\)/, "All and employee selection navigate directly to the report");
assert.match(header, /else params.delete\("person"\)/, "Self clears selected employee");
assert.match(header, /params.delete\("employee"\)/, "Scope transitions clear employee search");
assert.match(header, /params.set\("page","1"\)/, "Scope selection resets pagination");
assert.match(header, /event.key==="Escape"/, "Escape dismisses the scope dropdown");
assert.doesNotMatch(header, /<nav aria-label="Daily Report visibility"/, "Old segmented Self/All control must be removed");
for(const label of ["Today","90D","MTD","YTD","All time","Custom"]){
  assert.ok(header.includes(`label:"${label}"`),`Period menu missing ${label}`);
}
assert.match(header, /<ReportDateRangePicker/, "Use existing exact-style shared calendar");
assert.match(header, /onRangeComplete=\{\(start,end\)=>/, "Completing both custom dates activates custom period");
assert.match(header, /params\.set\("page","1"\)/, "Date and scope transitions reset detail pagination");
assert.match(header, /params\.delete\("person"\)/, "Self All changes don't retain a different employee's selection");
assert.doesNotMatch(page, /DailyReportQuickFilters|<nav|type="date"/, "Remove entire white date and scope section");
assert.match(page, /resolveDailyReportPeriod\(query\)/);
assert.match(page, /from: periodRange\.from, to: periodRange\.to/, "Apply period range to Self and selected employee events");
assert.match(period, /period==="today"/, "Today filters the report to the current IST calendar date");
assert.match(period, /query\.period : "today"/, "Missing period defaults to Today on the server");
assert.match(header, /value as Period:"today"/, "Missing period displays Today in the client filter");
assert.match(period, /period==="mtd"/);
assert.match(period, /period==="ytd"/);
assert.match(period, /period==="custom"/);
assert.match(period, /89\*86400000/, "90D includes current and 89 previous calendar days");
assert.match(period, /query\.from>query\.to \|\| query\.to>today/, "Invalid future and inverted dates fail closed");
assert.match(loader, /dailyReportRangeWindow\(options\.from,options\.to\)/);
assert.match(loader, /if\(window\) q=q\.gte\("created_at",window\.from\)\.lt\("created_at",window\.to\)/);
assert.match(loader, /if\(window\) q=q\.gte\("finalized_at",window\.from\)\.lt\("finalized_at",window\.to\)/);
assert.match(loader, /if\(window\) q=q\.gte\("converted_at",window\.from\)\.lt\("converted_at",window\.to\)/);
assert.match(endpoint, /loadDailyReportEmployeeDirectory\(profile\)/, "Employee dropdown uses server-authorized list");
assert.doesNotMatch(loader, /\.insert\(|\.update\(|\.delete\(|\.upsert\(/, "No changes to business records");
const css=read("../app/globals.css");
assert.ok(css.includes("z-index: 40;") && css.includes(".reports-reference-header"), "Daily Report header stacks above activity summary");
assert.ok(css.includes('[aria-label="Daily Report employee selector"]') && css.includes("z-index: 50;"), "Employee picker has a higher stacking level");
assert.ok(header.includes('absolute left-0 top-[calc(100%+4px)] z-[80]'), "Employee search dropdown remains above the report content");
const panel=read("../components/reports/daily-self-activity-panel.tsx");
assert.match(panel,/text-\[10px\] font-extrabold uppercase tracking-wide text-\[#243752\]/,"Column headings are darker than record values");
assert.match(header,/document\.addEventListener\("pointerdown",outside\)/,"Outside-click handling supports touch and mouse pointers");
assert.match(header,/max-h-\[min\(300px,50dvh\)\]/,"Employee menu remains usable on short viewports");
assert.match(header,/min-h-10 w-full rounded-md px-3 py-2/,"Dropdown options provide accessible touch targets");
assert.match(header,/z-\[80\] min-w-\[158px\]/,"Period menu opens above content on narrow screens");
assert.match(header,/params\.set\("period",period\)/,"Period selections update the URL query");
assert.match(header,/router\.push\(\`\$\{pathname\}\?\$\{params\.toString\(\)\}\`,\{scroll:false\}\)/,"Period selection navigates to filtered records");

assert.ok(panel.includes("<DailyReportHeaderScopes canViewAll={canViewAll} />"), "Authorized Self/employee selector sits beside summary title");
assert.ok(panel.includes("<DailyReportHeaderPeriod />"), "Date period dropdown lives in purple summary toolbar");
assert.ok(panel.includes('} RECORDS</span>'), "Activity count reads N RECORDS");
assert.ok(panel.includes('text-white'), "Record count uses white foreground");
assert.ok(page.includes('canViewAll={canViewAll}'), "Employee access permission is passed to summary toolbar");
assert.ok(css.includes("> .reports-reference-header {") && css.includes("display: none;"), "Redundant Reports heading is hidden on Daily Report only");
assert.ok(css.includes(".daily-report-reference .daily-report-panel {") && css.includes("overflow: visible;"), "Summary menus are not clipped by the activity panel");
assert.ok(css.includes(".daily-report-panel-title .daily-report-total-badge {") && css.includes("color: #fff !important;"), "Record total remains visible in white");
assert.ok(header.includes("w-[112px] max-w-[36vw]"), "Scope dropdown is compact beside the activity title");
assert.ok(!header.includes("w-[clamp(124px,18vw,235px)]"), "Old oversized Self dropdown must not return");
assert.ok(css.includes('[aria-label="Daily Report employee selector"] .daily-report-header-select {') && css.includes("width: 112px;"), "Compact scope width overrides the shared header style");
assert.ok(header.includes('min-w-[132px]'), "Date period filter retains its original width");
assert.ok(panel.includes("md:min-h-[calc(100dvh-80px)]"), "Desktop Daily Report fills available screen height");
assert.ok(panel.includes("min-h-[calc(100dvh-145px)]"), "Mobile Daily Report height tracks viewport");
assert.ok(panel.includes("relative z-10 mt-auto flex shrink-0 flex-wrap items-center justify-between"), "Pagination remains anchored at bottom");
console.log("Daily Report header layout, Today 90D MTD YTD All time Custom, and IST range source filtering verified.");
