import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { existsSync } from "node:fs";
const read = path => readFileSync(fileURLToPath(new URL(path, import.meta.url)), "utf8");
const stages = read("../components/claim-manager/operations-claim-stages.tsx");
const header = read("../components/spot-survey/spot-survey-workspace-v2.tsx");

assert.match(stages, /name: "spot_survey_done_date", label: "Spot Survey Done Date \*", type: "date"/);
assert.match(stages, /name: "surveyor_name"/);
assert.match(stages, /name: "surveyor_email"/);
assert.match(stages, /name: "surveyor_phone"/);
assert.match(stages, /const useAppDatePicker = field\.type === "date"/);
assert.match(stages, /<AppStyleDateInput name=\{field\.name\} value=\{value\} required=\{required\}/);
assert.ok(stages.includes('vehicleDeliveryCompact ? "h-[34px] max-w-full px-3"'), "Preserve Vehicle Delivery compact date variant");
assert.ok(stages.includes('relative flex ${billingCompact ? "mt-1 h-[34px] max-w-full px-2"'), "All Operations dates use 34px compact styling");
assert.doesNotMatch(stages, /h-full min-h-9/, "Do not stretch date input to label height");
assert.match(stages, /type="date"/,"Preserve accessible native calendar input");
assert.match(header, /vehicle: "\/assets\/customer-3d-icons\/brand_new_vehicle\.png"/, "Vehicle Number must use the existing 3D vehicle artwork.");
assert.match(header, /<Info label="Vehicle No\." title=\{vehicleNumber\} logo=\{<HeaderIcon src=\{claimHeaderIcons\.vehicle\} alt="Vehicle" \/>/, "Vehicle Number must display the 3D icon.");
assert.doesNotMatch(header, /customer-3d-icons\/my_vehicles\.png/, "Do not restore the old multiple-vehicle header illustration.");
assert.match(header, /import \{ CarFront \} from "lucide-react"/, "Keep the clear manufacturer fallback icon.");
assert.ok(existsSync(fileURLToPath(new URL("../public/assets/customer-3d-icons/brand_new_vehicle.png", import.meta.url))), "Chosen 3D vehicle artwork must exist.");
console.log("Operations Stage 2 date height and vehicle header icon regression passed.");
