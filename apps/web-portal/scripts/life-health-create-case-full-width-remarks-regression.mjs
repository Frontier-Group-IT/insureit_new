import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const form = readFileSync(new URL("../components/life-health-policy-form.tsx", import.meta.url), "utf8");
const editor = readFileSync(new URL("../components/life-health-remarks-editor.tsx", import.meta.url), "utf8");
const action = readFileSync(new URL("../app/policies/life-health-policy-actions.ts", import.meta.url), "utf8");
const caseDetail = readFileSync(new URL("../components/life-health-case-detail.tsx", import.meta.url), "utf8");
const registerPage = readFileSync(new URL("../app/policies/life-health-cases/page.tsx", import.meta.url), "utf8");

const editorTag = '<LifeHealthRemarksEditor value={form.remarks} onChange={(value) => update("remarks", value)} disabled={isPending} compact />';
const start = form.indexOf('<Section number="04" title="Premium & payment"');
const end = form.indexOf('</Section>', start);
const section = form.slice(start, end);
const historyIndex = form.indexOf('id="life-health-onboarding-remarks"');
const footerIndex = form.indexOf('id="life-health-onboarding-footer"');
assert.ok(start > 0 && end > start && historyIndex > end && footerIndex > historyIndex, "Remarks history must follow the premium row, above footer actions");
assert.match(section, /contentClassName="md:grid-cols-3"/, "Premium, Payment Mode, Remarks share three desktop columns");
assert.ok(section.indexOf('label="Premium amount"') < section.indexOf('label="Payment mode"'), "Premium precedes payment");
assert.ok(section.indexOf('label="Payment mode"') < section.indexOf(editorTag), "Add Remark is third field beside Payment Mode");
assert.equal(form.split(editorTag).length - 1, 1, "Only one Add Remark control exists");
assert.doesNotMatch(form.slice(footerIndex), /LifeHealthRemarksEditor/, "No redundant remarks input in the bottom footer");
assert.match(form, /form\.remarks\.trim\(\) \? <section id="life-health-onboarding-remarks" aria-label="Remarks history"/, "Only added remarks show a separate read-only history");
assert.match(form, /aria-label="Added remarks"/, "Remarks history uses its own labeled region");
assert.match(form, /whitespace-pre-wrap break-words/, "Multiline entries remain readable");
assert.match(editor, /compact \? \(/, "Compact editor renders the whole-width Add Remark button");
assert.match(editor, /h-10 w-full items-center justify-center gap-2 rounded-xl/, "Add Remark button matches payment input height");
assert.match(editor, /aria-label="Add Remark"/, "Button is accessible");
assert.match(editor, /onChange\(previous \?/, "New draft remarks append rather than replace history");
assert.match(action, /remarks:remarks\|\|null/, "Create Case still persists submitted remarks");
assert.match(caseDetail, /savedRemarks\.trim\(\)\|\|"No remarks added yet\."/,"Case Details Remarks tab continues reading saved history");
assert.match(registerPage, /remarks: row\.remarks \|\| ""/, "Case Register retains persisted remarks mapping");
console.log("Life/Health Create Case premium/payment/remarks row and saved remarks history regression passed.");
