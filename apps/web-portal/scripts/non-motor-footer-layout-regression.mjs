import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const src = readFileSync(new URL("../components/non-motor-unified-mode.tsx", import.meta.url), "utf8");
const start = src.indexOf('<section aria-label="Non-Motor policy documents and save actions"');
const end = src.indexOf("</section>", start);
assert.ok(start >= 0 && end > start, "Non-Motor documents and actions must share a normal-flow section");
const footer = src.slice(start, end);
assert.match(footer, /<NonMotorDocumentPicker/);
assert.match(footer, /flex flex-wrap items-center justify-between gap-3/, "Documents and Save/Cancel are in a single responsive row");
assert.doesNotMatch(footer, /border-b border-\[#E7ECF3\]/, "No separate document and action rows");
assert.match(footer, /flex shrink-0 items-center justify-end gap-2/, "Cancel and save remain grouped on the right");
assert.match(footer, />Cancel<\/Link>/);
assert.match(footer, /onClick=\{\(\)=>submit\(\)\}/, "Final-save action must remain available via submission wrapper");
assert.ok(footer.indexOf("<NonMotorDocumentPicker") < footer.indexOf(">Cancel</Link>"), "Document uploads must precede final actions");
assert.doesNotMatch(footer, /\bfixed\b|\bsticky\b|bottom-0|z-40/, "Footer controls must not be viewport-fixed");
assert.match(src, /<NonMotorLiveSummary/, "Non-Motor summary must remain available");
const picker = readFileSync(new URL("../components/non-motor-document-picker.tsx", import.meta.url), "utf8");
assert.match(picker, /<button type="button" onClick=\{viewSavedDocument\} title=\{existingDocument\.fileName\}/, "Every saved document filename opens the document");
assert.match(picker, /\{existingDocument\.fileName\}<\/span>/, "Use actual saved filename as action label");
assert.match(picker, /<button type="button" onClick=\{\(\) => inputRef\.current\?\.click\(\)\} disabled=\{deleting\} aria-label=/, "Every saved document has a dedicated Replace icon");
assert.match(picker, /aria-label=\{\`Replace \$\{label\}\`\}/, "Replace icon is accessible");
assert.doesNotMatch(picker, /onClick=\{viewSavedDocument\} aria-label=\{\`View \$\{label\}\`\}/, "Saved filename replaces redundant view icon");
assert.match(picker, /onDeleteExisting \?/, "Existing delete control stays available");
const issued = readFileSync(new URL("../components/life-health-issued-policy-edit-form.tsx", import.meta.url), "utf8");
assert.match(issued, /documentLabels\.map\(\(\[type,label\]\)/, "Life/Health applies the same document controls across all issued document categories");
assert.match(issued, /aria-label=\{\`Open \$\{doc\.fileName\}\`\}/, "Life/Health saved filename opens its document");
assert.match(issued, /\{doc\.fileName\}<\/span>/, "Life/Health displays the actual saved filename");
assert.match(issued, /aria-label=\{\`Replace \$\{label\}\`\}/, "Life/Health retains a dedicated replace icon");
assert.doesNotMatch(issued, /aria-label=\{\`View \$\{label\}\`\}/, "Life/Health has no separate view icon");
assert.match(issued, /aria-label=\{\`Delete \$\{label\}\`\}/, "Life/Health retains delete action");
console.log("Non-Motor document and action footer layout regression passed");
