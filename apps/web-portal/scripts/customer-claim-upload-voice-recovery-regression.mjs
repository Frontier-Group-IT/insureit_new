import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const read=(path)=>readFileSync(fileURLToPath(new URL(path,import.meta.url)),"utf8");
const upload=read("../app/customer/(protected)/claims/[id]/stage/[stage]/upload-action.ts");
const config=read("../next.config.mjs");
const multi=read("../components/customer-portal/customer-claim-multiple-upload.tsx");
const voice=read("../components/customer-portal/customer-claim-voice-recorder.tsx");
const evidence=read("../components/customer-portal/customer-claim-evidence-workspace.tsx");
assert.match(config,/source: "\/customer\/spot-intimation", headers: voiceLabHeaders/,"Allow customer microphone on Spot Intimation");
assert.match(config,/source: "\/customer\/claims\/:id\/stage\/:stage", headers: voiceLabHeaders/,"Allow customer microphone on claim stage");
assert.match(config,/microphone=\(self\)/,"Microphone remains same-origin only");
assert.match(config,/microphone=\(\)/,"Other routes remain microphone restricted");
assert.match(upload,/milestone_key === "claim_intimation"/,"Stage 2 upload lock matches Spot Intimation edit lock");
assert.doesNotMatch(upload,/milestone_key === "spot_status"/,"Do not use incorrect Stage 2 key");
assert.match(upload,/uploadedCount: 1/,"Single upload returns confirmed count");
assert.match(multi,/router\.refresh\(\)/,"Successful bulk upload refreshes document list");
assert.match(multi,/CustomerErrorDialog/,"Bulk upload errors use popup");
assert.match(voice,/navigator\.mediaDevices\.getUserMedia\(\{ audio: true \}\)/,"Microphone request preserved");
assert.match(voice,/Windows microphone privacy settings/,"Denied microphone message checks OS access");
assert.match(voice,/router\.refresh\(\)/,"Successful voice upload refreshes document list");
assert.match(voice,/CustomerErrorDialog/,"Voice errors use popup");
assert.match(evidence,/type:"Other Document"/,"Bulk uploads are visible");
assert.match(evidence,/type:"Incident Voice Note"/,"Voice notes are visible");
