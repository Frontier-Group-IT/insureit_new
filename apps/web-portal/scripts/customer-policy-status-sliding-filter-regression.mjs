import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = path => readFileSync(resolve(root, path), "utf8");
const base = "app/customer/(protected)/policies/";
const page = read(base + "page.tsx");
const filter = read(base + "policy-status-sliding-filter.tsx");
const source = read(base + "policy-source-filter.tsx");
assert.match(page, /<PolicyStatusDropdown accountId=\{account.id\}/);
assert.match(filter, /\["all", "active", "due", "expired"\]/);
assert.match(filter, /<select/);
assert.match(filter, /aria-label="Filter policy status"/);
assert.match(filter, /value=\{normalized\}/);
assert.match(filter, /\{labels\[index\]\} \{counts\[value\]\}/);
assert.match(filter, /router\.push\(/);
assert.match(filter, /params\.set\("q", query\)/);
assert.match(filter, /params\.set\("source", source\)/);
assert.match(filter, /params\.set\("status", next\)/);
assert.match(filter, /new URLSearchParams\(\{ account: accountId \}\)/);
assert.doesNotMatch(filter, /setTimeout|translateX|grid-cols-4/);
for (const control of [filter, source, page]) assert.match(control, /h-10 w-fit shrink-0/);
console.log("Customer Policy compact status dropdown regression passed");
